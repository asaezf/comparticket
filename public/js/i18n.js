/**
 * Que idioma se ensena.
 *
 * Manda lo que hayas elegido a mano; si no has elegido nada, el del movil; y
 * si ese no lo tenemos, ingles. Se guarda en el movil y no en el servidor:
 * no hay cuentas de usuario, y el idioma es cosa de quien mira la pantalla,
 * no del grupo.
 */
const IDIOMAS = ['es', 'en', 'no', 'pl', 'fr', 'it', 'de'];

function detectLang() {
  try {
    const guardado = localStorage.getItem('ct_idioma');
    if (guardado && IDIOMAS.indexOf(guardado) >= 0) return guardado;
  } catch (_) {}
  const n = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
  // 'nb' y 'nn' son las dos formas escritas del noruego.
  if (n.startsWith('nb') || n.startsWith('nn')) return 'no';
  for (const c of IDIOMAS) if (n.startsWith(c)) return c;
  return 'en';
}

const lang = detectLang();
const t = translations[lang];

/**
 * La fecha y la hora de un ticket, sin mezclar dos fuentes distintas.
 *
 * El papel puede traer fecha y hora, ninguna de las dos, o solo una. Elegir
 * cada una por su lado —la fecha del papel si hay, si no la de cuando se
 * escaneó; la hora del papel si hay, si no ninguna— escondía un fallo real:
 * `receiptDate` es una fecha SIN hora ("2026-08-23"), y `new Date()` sobre
 * ese texto la interpreta como medianoche UTC. En Madrid eso son las 2 de la
 * madrugada — así que cualquier ticket con fecha pero sin hora (la mayoría:
 * muchos papeles no imprimen la hora, o Gemini no la encuentra) enseñaba una
 * hora fabricada de la nada. Comprobado: "2026-08-23" salía como "02:00".
 *
 * Aquí se elige un origen ENTERO: o la fecha y la hora vienen las dos del
 * papel, o las dos vienen de cuando se escaneó — nunca una de cada.
 */
function fechaDelTicket(tk) {
  if (tk && tk.receiptDate) {
    // "YYYY-MM-DD" a mano, en local. `new Date("YYYY-MM-DD")` la interpreta
    // como medianoche UTC, y en husos al oeste de Greenwich eso puede
    // desplazar el DÍA que se ve un día hacia atrás.
    const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(tk.receiptDate);
    const fecha = m ? new Date(+m[1], +m[2] - 1, +m[3]) : new Date(tk.receiptDate);
    return { fecha, horaTexto: tk.receiptTime || null, delPapel: true };
  }
  const fecha = new Date((tk && tk.createdAt) || Date.now());
  const horaTexto = isNaN(fecha) ? null
    : fecha.toLocaleTimeString(lang === 'es' ? 'es-ES' : 'en-US', { hour: '2-digit', minute: '2-digit' });
  return { fecha, horaTexto, delPapel: false };
}

/**
 * Termina la animación de "el ticket sale de la impresora" sin recortar nada.
 *
 * La animación crece el `max-height` desde 0, y como es `forwards` el valor
 * final se queda fijo para siempre. Con un tope fijo, cualquier ticket más
 * largo quedaba cortado de forma permanente — se comía el total en la pantalla
 * de revisión y media lista en la de marcar.
 *
 * Aquí se mide el alto real del contenido y se pasa al CSS, y en cuanto
 * termina la animación se le quitan todas las ataduras al ticket.
 *
 * Hay que llamarla DESPUÉS de pintar el contenido, y otra vez si el contenido
 * cambia de alto mientras aún se está imprimiendo (añadir una línea, desplegar
 * la ayuda).
 */
function fitTicket(el) {
  el = el || document.getElementById('ticket');
  if (!el) return;

  // Ya terminó: no hay nada que atar.
  if (el.classList.contains('printed')) return;

  const liberar = () => {
    el.classList.add('printed');
    el.classList.remove('printing');
  };

  if (!el.classList.contains('printing')) return liberar();

  // scrollHeight ignora el max-height que impone la animación, así que da el
  // alto de verdad del contenido. El margen extra evita que un redondeo deje
  // la última línea a medias.
  const alto = el.scrollHeight + 40;
  el.style.setProperty('--ticket-h', alto + 'px');

  if (!el.dataset.fitBound) {
    el.dataset.fitBound = '1';
    el.addEventListener('animationend', e => {
      if (e.animationName === 'ticketEmerge') liberar();
    });
    // Red de seguridad: si la animación no llega a emitir el evento (pestaña
    // en segundo plano, `prefers-reduced-motion`, un navegador raro), el
    // ticket se libera igual. Nunca puede quedarse recortado.
    setTimeout(liberar, 4200);
  }
}
